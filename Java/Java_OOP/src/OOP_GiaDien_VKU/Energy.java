package OOP_GiaDien_VKU;

public class Energy {
	private String madien;
	private int giadien;

	public Energy() {

	}

	public Energy(String madien, int giadien) {
		this.madien = madien;
		this.giadien = giadien;
	}

	public String getMadien() {
		return madien;
	}

	public void setMadien(String madien) {
		this.madien = madien;
	}

	public int getGiadien() {
		return giadien;
	}

	public void setGiadien(int giadien) {
		this.giadien = giadien;
	}

	
	
}
