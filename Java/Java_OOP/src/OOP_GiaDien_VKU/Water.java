package OOP_GiaDien_VKU;

public class Water {
	private String manuoc;
	private int gianuoc;

	public Water() {

	}

	public Water(String manuoc, int gianuoc) {
		this.manuoc = manuoc;
		this.gianuoc = gianuoc;
	}

	public String getManuoc() {
		return manuoc;
	}

	public void setManuoc(String manuoc) {
		this.manuoc = manuoc;
	}

	public int getGianuoc() {
		return gianuoc;
	}

	public void setGianuoc(int gianuoc) {
		this.gianuoc = gianuoc;
	}



}
